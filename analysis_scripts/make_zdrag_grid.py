"""
Generate the CAMB-calibrated z_drag(omega_b, omega_m) lookup table.

The Eisenstein & Hu (1998) fitting formula for the drag redshift gives
z_d ~ 1021 for Planck-2018 densities, whereas modern recombination codes
(CAMB/recfast) give z_d ~ 1060; feeding the EH98 value into the numerical
sound-horizon integral would bias r_d by ~ +2.4%.  We therefore tabulate
z_drag from CAMB on a grid of physical densities covering the full prior
volume of the analysis, and interpolate at run time
(theory_module.background.z_drag).

Run once from the repository root (regenerates the .npz shipped in git):
    .venv/bin/python analysis_scripts/make_zdrag_grid.py

Grid conventions:
    omega_b = Omega_b h^2   in [0.019, 0.026]
    omega_m = Omega_m h^2   in [0.09, 0.22]  (total matter incl. Σm_ν = 0.06 eV)
CAMB is called with omch2 = omega_m - omega_b - omega_nu and fixed
Σm_ν = 0.06 eV, N_eff = 3.044 (standard); z_drag is insensitive to H0.
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import camb  # noqa: E402

from usf_constants import OMEGA_NU_H2  # noqa: E402

OUT = os.path.join(
    os.path.dirname(__file__), "..", "theory_module", "data", "zdrag_camb_grid.npz"
)

omega_b_grid = np.arange(0.019, 0.02601, 0.0005)
omega_m_grid = np.arange(0.09, 0.2201, 0.005)


def main():
    zdrag = np.empty((omega_b_grid.size, omega_m_grid.size))
    zstar = np.empty_like(zdrag)
    for i, wb in enumerate(omega_b_grid):
        for j, wm in enumerate(omega_m_grid):
            pars = camb.set_params(
                ombh2=wb,
                omch2=wm - wb - OMEGA_NU_H2,
                H0=67.36,  # irrelevant for z_drag/z_star (physical densities fixed)
                mnu=0.06,
                omk=0.0,
                As=2.1e-9,
                ns=0.9649,
                tau=0.0544,
            )
            derived = camb.get_background(pars).get_derived_params()
            zdrag[i, j] = derived["zdrag"]
            zstar[i, j] = derived["zstar"]
        print(f"omega_b = {wb:.4f} done ({i + 1}/{omega_b_grid.size})")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    np.savez(
        OUT,
        omega_b=omega_b_grid,
        omega_m=omega_m_grid,
        zdrag=zdrag,
        zstar=zstar,
        meta="CAMB {} | mnu=0.06 eV, Neff=3.044 | generated by make_zdrag_grid.py".format(
            camb.__version__
        ),
    )
    print(f"Saved {OUT}: zdrag in [{zdrag.min():.2f}, {zdrag.max():.2f}], "
          f"zstar in [{zstar.min():.2f}, {zstar.max():.2f}]")


if __name__ == "__main__":
    main()
